"use strict";
const assert = require("node:assert/strict");
const {parseAndEvaluate, evaluate} = require("../calc.js");
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-10,`${a} != ${b}`);
near(parseAndEvaluate("2 plus 3 times 4").result,14);
near(parseAndEvaluate("(18 minus 6) divided by 3").result,4);
near(parseAndEvaluate("12 percent of 80").result,9.6);
near(evaluate("-2 * (3 + 4)"),-14);
assert.throws(()=>evaluate("8 / 0"),/divide by zero/i);
assert.throws(()=>parseAndEvaluate("1,234.56"),/decimal/i);
assert.throws(()=>parseAndEvaluate("1,234", "comma"),/could mark/i);
near(parseAndEvaluate("1,5 plus 2", "comma").result,3.5);
near(parseAndEvaluate("1 point 5 plus 2").result,3.5);
near(parseAndEvaluate("open parenthesis 2 plus 3 close parenthesis").result,5);
assert.throws(()=>parseAndEvaluate("five cats"),/did not understand/i);
assert.throws(()=>parseAndEvaluate("5 dollars"),/Units:/i);
assert.throws(()=>parseAndEvaluate("2 ^ + 3"),/symbol|every part/i);
assert.throws(()=>parseAndEvaluate("2 é + 3"),/every part/i);
assert.throws(()=>parseAndEvaluate(".5 + 1"),/every part/i);
assert.throws(()=>evaluate("2 ** 4"),/expression/i);
assert.throws(()=>evaluate("(2 + 3"),/parentheses/i);
assert.throws(()=>evaluate("9 / (3 - 3)"),/divide by zero/i);
assert.throws(()=>evaluate("99999999999999999 * 999999999999999"),/supported range/i);
console.log("19 parser assertions passed");
